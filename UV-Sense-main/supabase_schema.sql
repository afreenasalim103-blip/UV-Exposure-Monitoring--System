-- Enable necessary extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

--------------------------------------------------------------------------------
-- 1. TABLES
--------------------------------------------------------------------------------

-- Table: tbl_skintype (Centralized skin types)
CREATE TABLE IF NOT EXISTS public.tbl_skintype (
    type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skintype_name TEXT NOT NULL UNIQUE, -- OILY, DRY, NORMAL, COMBINATION, SENSITIVE
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Insert default skin types
INSERT INTO public.tbl_skintype (skintype_name) VALUES 
('OILY'), ('DRY'), ('NORMAL'), ('COMBINATION'), ('SENSITIVE') 
ON CONFLICT (skintype_name) DO NOTHING;

-- Table: tbl_user
CREATE TABLE IF NOT EXISTS public.tbl_user (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    user_name TEXT,
    user_email TEXT,
    user_contact TEXT,
    user_photo TEXT,
    user_gender TEXT,
    user_status TEXT DEFAULT 'active',
    skintype_id BIGINT REFERENCES public.tbl_skintype(type_id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: tbl_admin
CREATE TABLE IF NOT EXISTS public.tbl_admin (
    id TEXT PRIMARY KEY, -- Using string ID as seen in admin_registration.dart
    admin_name TEXT,
    admin_email TEXT,
    admin_password TEXT, -- Kept because registration logic uses it, though Auth is preferred
    admin_contact TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: tbl_category
CREATE TABLE IF NOT EXISTS public.tbl_category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: tbl_level
CREATE TABLE IF NOT EXISTS public.tbl_level (
    level_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    level_name TEXT NOT NULL,
    level_description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: tbl_product
CREATE TABLE IF NOT EXISTS public.tbl_product (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name TEXT NOT NULL,
    product_description TEXT,
    category_id BIGINT REFERENCES public.tbl_category(category_id),
    level_id BIGINT REFERENCES public.tbl_level(level_id),
    price DOUBLE PRECISION,
    photo TEXT,
    spf_rating TEXT,
    sunscreen_type TEXT,
    stock INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: tbl_product_skintype (Junction Table for Multi-Skin Type Support)
CREATE TABLE IF NOT EXISTS public.tbl_product_skintype (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.tbl_product(product_id) ON DELETE CASCADE,
    skintype_id BIGINT REFERENCES public.tbl_skintype(type_id) ON DELETE CASCADE,
    UNIQUE(product_id, skintype_id)
);

-- Table: tbl_stock (Optional, but kept for legacy)
CREATE TABLE IF NOT EXISTS public.tbl_stock (
    stock_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.tbl_product(product_id) ON DELETE CASCADE,
    stock_count INTEGER,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: tbl_booking
CREATE TABLE IF NOT EXISTS public.tbl_booking (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES public.tbl_user(user_id) ON DELETE CASCADE,
    booking_status INTEGER DEFAULT 0, 
    booking_amount DOUBLE PRECISION DEFAULT 0,
    booking_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
