-- 3. PERMISSIVE POLICIES (Targeted to avoid ownership errors)
--------------------------------------------------------------------------------

DO $$ 
DECLARE 
    tbl_name TEXT;
BEGIN
    -- Only loop through tables we just created (starting with 'tbl_')
    FOR tbl_name IN 
        SELECT tablename 
        FROM pg_tables 
        WHERE schemaname = 'public' AND tablename LIKE 'tbl_%'
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', tbl_name);
        EXECUTE format('DROP POLICY IF EXISTS "Global Permissive" ON public.%I', tbl_name);
        EXECUTE format('CREATE POLICY "Global Permissive" ON public.%I FOR ALL USING (true) WITH CHECK (true)', tbl_name);
    END LOOP;
END $$;

-- Storage Policies (Wrapped in EXCEPTION block or simplified)
-- Note: Modifying storage.objects RLS sometimes fails if not superuser, 
-- but policies can usually be added if RLS is already enabled.
DO $$ 
BEGIN
    -- Try to enable RLS on storage.objects (if possible)
    BEGIN
        ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
    EXCEPTION WHEN others THEN
        RAISE NOTICE 'Could not alter storage.objects, it may already be managed or restricted.';
    END;

    -- Create a broad policy for all storage objects
    DROP POLICY IF EXISTS "Global Storage Permissive" ON storage.objects;
    CREATE POLICY "Global Storage Permissive" ON storage.objects FOR ALL USING (true) WITH CHECK (true);
END $$;

--------------------------------------------------------------------------------
-- 4. PERMISSIONS (Targeted to avoid ownership errors)
--------------------------------------------------------------------------------

-- Grant permissions ONLY on the tables we created
DO $$ 
DECLARE 
    tbl_name TEXT;
BEGIN
    FOR tbl_name IN 
        SELECT tablename 
        FROM pg_tables 
        WHERE schemaname = 'public' AND tablename LIKE 'tbl_%'
    LOOP
        EXECUTE format('GRANT ALL ON TABLE public.%I TO postgres, anon, authenticated, service_role', tbl_name);
    END LOOP;
END $$;

-- Grant on sequences (usually fine as they are own by the tables)
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO postgres, anon, authenticated, service_role;
GRANT ALL ON ALL FUNCTIONS IN SCHEMA public TO postgres, anon, authenticated, service_role;

