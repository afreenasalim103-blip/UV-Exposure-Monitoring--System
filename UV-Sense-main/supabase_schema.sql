-- Table: tbl_dermatologist
CREATE TABLE IF NOT EXISTS public.tbl_dermatologist (
    dermatologist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dermatologist_name TEXT,
    dermatologist_email TEXT,
    dermatologist_contact TEXT,
    dermatologist_address TEXT,
    dermatologist_photo TEXT,
    dermatologist_status TEXT DEFAULT 'accepted',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
