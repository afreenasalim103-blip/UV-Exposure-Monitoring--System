-- Table: tbl_cart
CREATE TABLE IF NOT EXISTS public.tbl_cart (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES public.tbl_booking(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.tbl_product(product_id) ON DELETE CASCADE,
    cart_quantity INTEGER DEFAULT 1,
    cart_status INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Table: tbl_complaint
CREATE TABLE IF NOT EXISTS public.tbl_complaint (
    complaint_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES public.tbl_user(user_id) ON DELETE CASCADE,
    complaint_title TEXT,
    complaint_content TEXT,
    complaint_reply TEXT,
    complaint_status INTEGER DEFAULT 0,
    complaint_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
